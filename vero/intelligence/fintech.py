def _deduplicate(values: list[str]) -> list[str]:
    """
    Return a case-insensitive, order-preserving list of unique strings.
    """

    seen: set[str] = set()
    result: list[str] = []

    for value in values:
        if not isinstance(value, str):
            raise TypeError(
                "Ontology list entries must be strings. "
                f"Received {type(value).__name__}: {value!r}"
            )

        cleaned = value.strip()
        normalized = cleaned.casefold()

        if cleaned and normalized not in seen:
            seen.add(normalized)
            result.append(cleaned)

    return result


def _deduplicate_nested_lists(
    mapping: dict[str, list[str]],
) -> dict[str, list[str]]:
    """
    Deduplicate every list stored in a string-to-list dictionary.
    """

    return {
        name: _deduplicate(values)
        for name, values in mapping.items()
    }


def _normalize_fintech_ontology() -> None:
    """
    Remove duplicate values throughout the FinTech ontology.
    """

    list_fields = [
        "aliases",
        "technologies",
        "products",
        "customers",
        "business_models",
        "competitors",
        "yc_tags",
        "github_topics",
        "problems_solved",
    ]

    for field in list_fields:
        values = FINTECH[field]

        if not isinstance(values, list):
            raise TypeError(
                f"FINTECH[{field!r}] must be a list."
            )

        FINTECH[field] = _deduplicate(values)

    nested_fields = [
        "subindustries",
        "risk_indicators",
        "positive_signals",
    ]

    for field in nested_fields:
        values = FINTECH[field]

        if not isinstance(values, dict):
            raise TypeError(
                f"FINTECH[{field!r}] must be a dictionary."
            )

        FINTECH[field] = _deduplicate_nested_lists(values)


def validate_fintech_ontology() -> None:
    """
    Raise an error if the FinTech ontology has an invalid structure.
    """

    required_fields = {
        "name",
        "aliases",
        "subindustries",
        "technologies",
        "products",
        "customers",
        "business_models",
        "competitors",
        "yc_tags",
        "github_topics",
        "problems_solved",
        "signals",
        "risk_indicators",
        "positive_signals",
    }

    missing_fields = required_fields.difference(FINTECH)

    if missing_fields:
        raise ValueError(
            "FinTech ontology is missing required fields: "
            f"{sorted(missing_fields)}"
        )

    if FINTECH["name"] != "Financial Technology":
        raise ValueError(
            "FINTECH['name'] must be 'Financial Technology'."
        )

    if not isinstance(FINTECH["aliases"], list):
        raise TypeError("FINTECH['aliases'] must be a list.")

    if not FINTECH["aliases"]:
        raise ValueError(
            "The FinTech ontology must contain at least one alias."
        )

    if not isinstance(FINTECH["subindustries"], dict):
        raise TypeError(
            "FINTECH['subindustries'] must be a dictionary."
        )

    if not FINTECH["subindustries"]:
        raise ValueError(
            "The FinTech ontology must contain subindustries."
        )

    for subindustry_name, terms in FINTECH["subindustries"].items():
        if not isinstance(subindustry_name, str):
            raise TypeError(
                "Every FinTech subindustry name must be a string."
            )

        if not isinstance(terms, list):
            raise TypeError(
                f"Subindustry {subindustry_name!r} must contain a list."
            )

        if not terms:
            raise ValueError(
                f"Subindustry {subindustry_name!r} has no terms."
            )

    if not isinstance(FINTECH["signals"], dict):
        raise TypeError("FINTECH['signals'] must be a dictionary.")

    for signal_name, signal_value in FINTECH["signals"].items():
        if not isinstance(signal_name, str):
            raise TypeError("Signal names must be strings.")

        if not isinstance(signal_value, (int, float)):
            raise TypeError(
                f"Signal {signal_name!r} must be numeric."
            )

        if not 0 <= signal_value <= 1:
            raise ValueError(
                f"Signal {signal_name!r} must be between 0 and 1."
            )

    for field in ("risk_indicators", "positive_signals"):
        groups = FINTECH[field]

        if not isinstance(groups, dict):
            raise TypeError(
                f"FINTECH[{field!r}] must be a dictionary."
            )

        for group_name, terms in groups.items():
            if not isinstance(group_name, str):
                raise TypeError(
                    f"Every key in FINTECH[{field!r}] must be a string."
                )

            if not isinstance(terms, list):
                raise TypeError(
                    f"FINTECH[{field!r}][{group_name!r}] "
                    "must be a list."
                )


_normalize_fintech_ontology()
